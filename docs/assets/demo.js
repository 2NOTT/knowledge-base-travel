export function findDemoExample(query, history = []) {
  const cityIn = text => /杭州|西湖/.test(text) ? '杭州' : /云南|大理|丽江/.test(text) ? '云南' : /成都/.test(text) ? '成都' : '';
  const topic = /住|酒店/.test(query) ? 'stay' : /美食|吃|火锅|小吃/.test(query) ? 'food' : /交通|机场|地铁/.test(query) ? 'transport' : 'route';
  const explicitCity = cityIn(query);
  if (!/住|酒店|路线|行程|玩|景点|美食|交通|机场|地铁|老城|吃|火锅|小吃|旅游|慢生活|自然|古城/.test(query)
      && !/^(成都|杭州|西湖|云南|大理|丽江)$/.test(query.trim())) return null;
  const city = explicitCity || history.filter(item => item.role === 'user').map(item => cityIn(item.text || '')).filter(Boolean).at(-1) || '成都';
  return demoExamples.find(example => example.city === city && example.topic === topic)
    || (topic === 'route' ? demoExamples.find(example => example.city === city) : null);
}
